#!/usr/bin/env swift
// Embeds the artwork in Design/ in the design system as Swift source:
//
//   swift Scripts/embed-assets.swift
//
// Run it from anywhere after adding, changing or removing a file in Design/. Every PDF or
// PNG in a folder of Design/ becomes an `Artwork` named after the file, in an enum named
// after the folder: Design/DisplayPictures/tv.pdf is `Artwork.DisplayPictures.tv`. The
// result replaces Sources/ResoluteDesign/Assets/EmbeddedArtwork.swift; the tests fail
// until its bytes match Design/ again.
//
// The artwork is data in Swift rather than a SwiftPM resource because `Bundle.module`
// looks for its bundle at the root of the .app, where it can't be signed, and falls back
// to a build-folder path that doesn't exist on other Macs.
import Foundation

/// The file types NSImage draws. PDF keeps the artwork vector, so it is sharp at any size.
let embeddedTypes: Set<String> = ["pdf", "png"]
/// Characters of base64 per line of the generated literals.
let lineLength = 100

let root = URL(filePath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let design = root.appending(path: "Design", directoryHint: .isDirectory)
let output = root.appending(path: "Sources/ResoluteDesign/Assets/EmbeddedArtwork.swift")

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("embed-assets: \(message)\n".utf8))
    exit(1)
}

/// Whether `name` can be a Swift identifier as it is: ASCII letters, digits and
/// underscores, not starting with a digit (keywords are escaped separately).
func isIdentifier(_ name: String) -> Bool {
    let scalars = Array(name.unicodeScalars)
    guard let first = scalars.first, !("0"..."9").contains(first) else { return false }
    return scalars.allSatisfy { $0.isASCII && ($0 == "_" || CharacterSet.alphanumerics.contains($0)) }
}

/// Swift keywords a file could plausibly be named after, which need backticks.
let keywords: Set<String> = [
    "default", "case", "class", "enum", "extension", "func", "import", "in", "internal", "is", "let",
    "operator", "private", "protocol", "public", "return", "self", "static", "struct", "switch", "true",
    "false", "nil", "var", "where", "while", "for", "if", "else", "do", "try", "throw", "repeat", "guard",
]

func escaped(_ name: String) -> String {
    keywords.contains(name) ? "`\(name)`" : name
}

struct Entry {
    var folder: String
    var name: String
    var source: String
    var data: Data
}

let fileManager = FileManager.default
let folders: [URL]
do {
    folders = try fileManager.contentsOfDirectory(at: design, includingPropertiesForKeys: [.isDirectoryKey])
        .filter { (try? $0.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true }
        .sorted { $0.lastPathComponent < $1.lastPathComponent }
} catch {
    fail("can't read \(design.path(percentEncoded: false)): \(error.localizedDescription)")
}

var entries: [Entry] = []
for folder in folders {
    let folderName = folder.lastPathComponent
    guard isIdentifier(folderName), !keywords.contains(folderName) else {
        fail("Design/\(folderName) must be named like a Swift type (letters and digits, no spaces).")
    }
    let files = (try? fileManager.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)) ?? []
    for file in files.sorted(by: { $0.lastPathComponent < $1.lastPathComponent })
    where embeddedTypes.contains(file.pathExtension.lowercased()) {
        let name = file.deletingPathExtension().lastPathComponent
        guard isIdentifier(name) else {
            fail("Design/\(folderName)/\(file.lastPathComponent) must be named like a Swift property (letters and digits, no spaces).")
        }
        guard !entries.contains(where: { $0.folder == folderName && $0.name == name }) else {
            fail("Design/\(folderName) has two files named \(name).")
        }
        guard let data = try? Data(contentsOf: file), !data.isEmpty else {
            fail("can't read Design/\(folderName)/\(file.lastPathComponent), or it is empty.")
        }
        entries.append(Entry(folder: folderName, name: name, source: "Design/\(folderName)/\(file.lastPathComponent)", data: data))
    }
}
guard !entries.isEmpty else { fail("Design/ has no artwork to embed.") }

var generated = """
    // Generated by Scripts/embed-assets.swift from the artwork in Design/. Do not edit:
    // change the files in Design/ and run `swift Scripts/embed-assets.swift` again.


    """
var folderNames: [String] = []
for entry in entries where !folderNames.contains(entry.folder) {
    folderNames.append(entry.folder)
}
generated += "extension Artwork {\n"
for (index, folder) in folderNames.enumerated() {
    if index > 0 { generated += "\n" }
    generated += "    /// The artwork in Design/\(folder).\n"
    generated += "    enum \(folder) {\n"
    for (entryIndex, entry) in entries.filter({ $0.folder == folder }).enumerated() {
        if entryIndex > 0 { generated += "\n" }
        let base64 = entry.data.base64EncodedString()
        var lines: [Substring] = []
        var start = base64.startIndex
        while start < base64.endIndex {
            let end = base64.index(start, offsetBy: lineLength, limitedBy: base64.endIndex) ?? base64.endIndex
            lines.append(base64[start..<end])
            start = end
        }
        generated += "        /// \(entry.source), \(entry.data.count) bytes.\n"
        generated += "        static let \(escaped(entry.name)) = Artwork(\n"
        generated += "            source: \"\(entry.source)\",\n"
        generated += "            base64: \"\"\"\n"
        for line in lines {
            generated += "                \(line)\n"
        }
        generated += "                \"\"\"\n"
        generated += "        )\n"
    }
    generated += "    }\n"
}
generated += "\n    /// Every embedded file, in the order of Design/.\n"
generated += "    static let all: [Artwork] = [\n"
for entry in entries {
    generated += "        \(entry.folder).\(escaped(entry.name)),\n"
}
generated += "    ]\n"
generated += "}\n"

do {
    try fileManager.createDirectory(at: output.deletingLastPathComponent(), withIntermediateDirectories: true)
    try Data(generated.utf8).write(to: output, options: .atomic)
} catch {
    fail("can't write \(output.path(percentEncoded: false)): \(error.localizedDescription)")
}
let total = entries.reduce(0) { $0 + $1.data.count }
print("Embedded \(entries.count) files (\(total) bytes) in \(output.path(percentEncoded: false))")
